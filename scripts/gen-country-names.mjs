// Generates src/lib/country-names.ts — English country names for the admin dashboard.
//
// Baked into a file rather than resolved with Intl at runtime so the dashboard does not depend on
// which ICU build the Workers runtime happens to ship.
//
// Flags are emoji, built from the country code itself, so there is nothing to download and nothing
// to keep in sync. An earlier version self-hosted 252 PNGs; the owner preferred emoji, and emoji
// needs no assets at all.
//
// Re-run with:  node scripts/gen-country-names.mjs
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'

const display = new Intl.DisplayNames(['en'], { type: 'region' })
const A = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'.split('')
const codes = []
for (const a of A) {
  for (const b of A) {
    const cc = a + b
    let name
    try { name = display.of(cc) } catch { continue }
    // An unassigned code resolves to itself.
    if (!name || name === cc) continue
    codes.push([cc, name])
  }
}

const entries = codes.map(([cc, name]) => `  ${cc}: ${JSON.stringify(name)},`).join('\n')
writeFileSync(join(process.cwd(), 'src', 'lib', 'country-names.ts'), `// GENERATED by scripts/gen-country-names.mjs — do not edit by hand.
export const COUNTRY_NAMES: Record<string, string> = {
${entries}
}

/** Full name for an ISO-3166-1 alpha-2 code, falling back to the code itself. */
export function countryName(code: string): string {
  if (!code) return ''
  return COUNTRY_NAMES[code.toUpperCase()] ?? code.toUpperCase()
}

/**
 * Flag emoji for a country code, built from the two regional-indicator letters.
 *
 * Note for anyone reading this on Windows: Segoe UI Emoji has no regional-indicator glyphs, so these
 * render as the plain two letters there. That is a Windows font decision, not a bug here — and the
 * full country name sits next to it either way.
 */
export function countryFlag(code: string): string {
  const cc = (code || '').toUpperCase()
  if (!/^[A-Z]{2}$/.test(cc)) return ''
  return String.fromCodePoint(...[...cc].map((ch) => 0x1F1E6 + ch.charCodeAt(0) - 65))
}
`)
console.log(`[country-names] ${codes.length} regions written`)
