// Generates src/lib/country-names.ts — English country names for the admin dashboard.
//
// Baked into a file rather than resolved with Intl at runtime so the dashboard does not depend on
// which ICU build the Workers runtime happens to ship.
//
// Also downloads the flag images into public/flags.
//
// Emoji was tried and does not work here. A flag emoji is two regional-indicator letters that a font
// is supposed to draw as a flag, and Segoe UI Emoji — every Windows browser — has no such glyphs, so
// it draws the letters instead. The dashboard showed "AM Armenia", which is the exact thing the
// images replaced. LocaleFlag.tsx had already reached this conclusion for the language switcher.
//
// PNG at 80px wide, not SVG: the SVG set is 4.1MB because a dozen countries carry a full coat of
// arms (El Salvador alone is 244KB), all of it downloaded and rasterised to draw a 16px rectangle.
// The PNG set is ~440KB for 252 flags, largest 4KB. Self-hosted because the CSP is `img-src 'self'`,
// and because an admin page should not tell a CDN which countries its owner is looking at.
//
// Re-run with:  node scripts/gen-country-names.mjs
import { writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const OUT_DIR = join(process.cwd(), 'public', 'flags')
mkdirSync(OUT_DIR, { recursive: true })

const display = new Intl.DisplayNames(['en'], { type: 'region' })
const A = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'.split('')
const codes = []
for (const a of A) {
  for (const b of A) {
    const cc = a + b
    let name
    try { name = display.of(cc) } catch { continue }
    // An unassigned code resolves to itself.
    if (!name || name === cc) continue
    codes.push([cc, name])
  }
}

let ok = 0, missing = 0, i = 0
async function worker() {
  while (i < codes.length) {
    const [cc] = codes[i++]
    const file = join(OUT_DIR, `${cc.toLowerCase()}.png`)
    if (existsSync(file)) { ok++; continue }
    try {
      const r = await fetch(`https://flagcdn.com/w80/${cc.toLowerCase()}.png`)
      if (!r.ok) { missing++; continue }
      const buf = Buffer.from(await r.arrayBuffer())
      if (buf.length < 8 || buf[0] !== 0x89 || buf[1] !== 0x50) { missing++; continue }
      writeFileSync(file, buf)
      ok++
    } catch { missing++ }
  }
}
await Promise.all(Array.from({ length: 12 }, worker))
console.log(`[flags] ${ok} written, ${missing} unavailable`)

// Only codes whose file actually landed. Rendering an <img> for one of the ~28 regions with no flag
// would put a broken-image icon in the table.
const have = codes.filter(([cc]) => existsSync(join(OUT_DIR, cc.toLowerCase() + '.png'))).map(([cc]) => cc)

const entries = codes.map(([cc, name]) => `  ${cc}: ${JSON.stringify(name)},`).join('\n')
writeFileSync(join(process.cwd(), 'src', 'lib', 'country-names.ts'), `// GENERATED by scripts/gen-country-names.mjs — do not edit by hand.
export const COUNTRY_NAMES: Record<string, string> = {
${entries}
}

/** Full name for an ISO-3166-1 alpha-2 code, falling back to the code itself. */
export function countryName(code: string): string {
  if (!code) return ''
  return COUNTRY_NAMES[code.toUpperCase()] ?? code.toUpperCase()
}

/** Codes with a flag image in /public/flags. Checked before rendering, so never a broken image. */
export const FLAG_CODES = new Set(${JSON.stringify(have)})

/**
 * Path to a country's flag image, or null when we do not have one.
 *
 * An image rather than emoji: a flag emoji is two regional-indicator letters, and Windows fonts have
 * no glyphs for them, so every Windows browser renders "AM" instead of the flag.
 */
export function flagSrc(code: string): string | null {
  const cc = (code || '').toUpperCase()
  return FLAG_CODES.has(cc) ? '/flags/' + cc.toLowerCase() + '.png' : null
}
`)
console.log(`[country-names] ${codes.length} regions written`)
